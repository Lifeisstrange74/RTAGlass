"""Trace control flow of the VU1 microcode from each jump-table entry and summarise each microprogram.

The microcode image (from .vutext MPG uploads) starts with a jump table: 8 slots of {b target; nop} at
VU addresses 0x00, 0x10, ... 0x70. MSCAL/MSCALF in VIF packets call those slots.

Rules: branches have one delay slot; BAL calls a subroutine that returns with JR; an instruction with the
E bit ends the program after its delay slot.

Usage: python -I scripts/vu/vuflow.py   -> reference/vu/programs.md
"""
import collections
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from vudis import disasm_pair  # noqa: E402
from vutext import ELF, FILE_OFS, SIZE, OUTDIR, walk  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def load_image():
    blob = open(ELF, 'rb').read()[FILE_OFS:FILE_OFS + SIZE]
    _lines, vif = walk(blob)
    image = {}
    for _va, vuaddr, pairs in vif.mpgs:
        for k, (lo, hi) in enumerate(pairs):
            image[vuaddr + k * 8] = (lo, hi)
    return image, vif


def trace(image, entry):
    """Return (set of pcs, set of subroutine entries) reachable from entry, following BAL into callees."""
    seen, subs = set(), set()
    work = [entry]
    while work:
        pc = work.pop()
        while pc in image and pc not in seen:
            seen.add(pc)
            lo, hi = image[pc]
            up, low, flags, target = disasm_pair(lo, hi, pc)
            op = low.split(' ')[0]
            if 'E' in flags:
                seen.add(pc + 8)          # delay slot, then the program halts
                break
            if op == 'b':
                seen.add(pc + 8)
                pc = target
                continue
            if op == 'bal':
                seen.add(pc + 8)
                subs.add(target)
                work.append(target)
                pc += 16                  # returns here after JR
                continue
            if target is not None:        # conditional branch
                seen.add(pc + 8)
                work.append(target)
                pc += 16
                continue
            if op in ('jr', 'jalr'):
                seen.add(pc + 8)
                break
            pc += 8
    return seen, subs


def main():
    image, vif = load_image()
    entries = []
    for slot in range(0, 0x80, 0x10):
        lo, hi = image[slot]
        _u, low, _f, target = disasm_pair(lo, hi, slot)
        entries.append((slot, target))

    mscal_uses = collections.Counter(addr for _va, addr in vif.mscals)
    out = ['# VU1 microprograms (generated by scripts/vu/vuflow.py)', '',
           'Single microcode image: VU1 micro memory 0x0000-0x%04X, %d instructions, uploaded once from '
           '.vutext.' % (max(image) + 8, len(image)), '',
           '| Slot | Entry | Instrs reached | xgkick | clip | div/rsqrt | subroutines | MSCALs in .vutext |',
           '|---|---|---:|---:|---:|---:|---|---:|']
    owners = collections.defaultdict(set)
    for slot, entry in entries:
        pcs, subs = trace(image, entry)
        for pc in pcs:
            owners[pc].add(slot)
        texts = [disasm_pair(*image[pc], pc) for pc in sorted(pcs) if pc in image]
        xg = sum(t[1].startswith('xgkick') for t in texts)
        clip = sum(t[0].startswith('clip') for t in texts)
        div = sum(t[1].startswith(('div', 'rsqrt', 'sqrt')) for t in texts)
        out.append('| 0x%02X | 0x%04X | %d | %d | %d | %d | %s | %d |' % (
            slot, entry, len(pcs), xg, clip, div, ' '.join('0x%04X' % s for s in sorted(subs)) or '-',
            mscal_uses.get(slot, 0)))
    unreached = sorted(pc for pc in image if pc >= 0x80 and pc not in owners)
    shared = sorted(pc for pc, o in owners.items() if len(o) > 1)
    out += ['', 'Instructions shared by more than one program: %d. Unreached (dead or data): %d.' % (
        len(shared), len(unreached))]
    if unreached:
        runs, start, prev = [], unreached[0], unreached[0]
        for pc in unreached[1:] + [None]:
            if pc != prev + 8:
                runs.append('0x%04X-0x%04X' % (start, prev + 8))
                start = pc
            prev = pc if pc is not None else prev
        out.append('Unreached ranges: ' + ', '.join(runs))
    path = os.path.join(OUTDIR, 'programs.md')
    with open(path, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    sys.exit(main())
