"""Writes src/game/field/field_towns.inc from the ELF: the towns' table D_002BE438 (8 bytes a town: name
pointer, u16 block, u8 places, u8 cars) and each town's doors D_002C0698[town] (32 bytes a place: four corners
(x, z), the last two the side the car drives out by).

    python -I scripts/elf/gen_field_towns.py
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# The extracted disc: OriginalGameFiles next to the repo, or the folder in RTAGLASS_GAME.
GAME = os.environ.get('RTAGLASS_GAME', os.path.join(ROOT, '..', 'OriginalGameFiles'))
ELF = os.path.join(GAME, 'SLUS_203.98')
OUT = os.path.join(ROOT, 'src', 'game', 'field', 'field_towns.inc')
TOWNS = 0x002BE438
DOORS = 0x002C0698
COUNT = 22

elf = open(ELF, 'rb').read()
phoff, = struct.unpack_from('<I', elf, 0x1C)
count, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<6I', elf, phoff + 32 * i)[1:5] for i in range(count)]


def rd(va, n):
    for off, vaddr, _pa, size in segs:
        if vaddr <= va < vaddr + size:
            return elf[off + va - vaddr:off + va - vaddr + n]
    raise ValueError(hex(va))


def num(f):
    s = '%.6g' % f
    if 'e' not in s and '.' not in s:
        s += '.0'
    return s + 'f'


lines = ['// Generated by scripts/elf/gen_field_towns.py from the ELF (SLUS_203.98): the towns (D_002BE438: block,',
         '// places, cars) and their doors (D_002C0698[town] + 32 x place: four corners x, z).']
towns = []
for t in range(COUNT):
    _name, block, places, cars = struct.unpack('<IhBB', rd(TOWNS + 8 * t, 8))
    towns.append((block, places, cars))
    p, = struct.unpack('<I', rd(DOORS + 4 * t, 4))
    if not places:
        continue
    # My City's list goes on past its places and its cars' slots (23-28, all -1) to 29, the Big Tower's top, where
    # Roberts's pre-code 0x14 (9, 29) puts the car: a way out (corners 2 and 3) with no door (corners 0 and 1 -1).
    doors = places + cars + 1 if t == 9 else places
    lines.append('const FieldDoor kDoors%d[%d] = {' % (t, doors))
    for i in range(doors):
        v = struct.unpack('<8f', rd(p + 32 * i, 32))
        lines.append('    {{' + ', '.join(num(f) for f in v) + '}},')
    lines.append('};')
lines.append('const FieldTown kTowns[%d] = {' % COUNT)
for t, (block, places, cars) in enumerate(towns):
    lines.append('    {%d, %d, %d, %s},' % (block, places, cars, 'kDoors%d' % t if places else 'nullptr'))
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT)
