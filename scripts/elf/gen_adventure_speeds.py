"""Writes src/game/race/adventure_speeds.inc from the ELF: D_002A9B80, the AI's speed tables by race, 35 x
256 bytes (one per Adventure race 0-34: the towns' and the World Grand Prix's). Ai_Init (0x0024FCD8, asm 0x0024FE78)
gives an Adventure car not on a team (car flags & 0x30 == 0) the table of its race (info+0x20) on a path below 0x13;
the Quick Race maps each path to one of these through D_002AC080 and D_002AC098, which the converted course paths
(data/ai/Cnn.txt) already hold.

    python -I scripts/elf/gen_adventure_speeds.py
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# The extracted disc: OriginalGameFiles next to the repo, or the folder in RTAGLASS_GAME.
GAME = os.environ.get('RTAGLASS_GAME', os.path.join(ROOT, '..', 'OriginalGameFiles'))
ELF = os.path.join(GAME, 'SLUS_203.98')
OUT = os.path.join(ROOT, 'src', 'game', 'race', 'adventure_speeds.inc')
TABLE = 0x002A9B80
RACES = 35

elf = open(ELF, 'rb').read()
phoff, = struct.unpack_from('<I', elf, 0x1C)
count, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<6I', elf, phoff + 32 * i)[1:5] for i in range(count)]


def rd(va, n):
    for off, vaddr, _pa, size in segs:
        if vaddr <= va < vaddr + size:
            return elf[off + va - vaddr:off + va - vaddr + n]
    raise ValueError(hex(va))


lines = ['// Generated by scripts/elf/gen_adventure_speeds.py from the ELF (SLUS_203.98): D_002A9B80, the AI\'s speed',
         '// table (a byte per zone, 5 km/h units, bit 7 a flag) for each Adventure race 0-34.',
         'const uint8_t kAdventureSpeeds[%d][256] = {' % RACES]
for r in range(RACES):
    t = rd(TABLE + 256 * r, 256)
    lines.append('    {  // race %d' % r)
    for k in range(0, 256, 16):
        lines.append('        ' + ', '.join('0x%02X' % b for b in t[k:k + 16]) + ',')
    lines.append('    },')
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT)
