"""Writes src/game/story/adventure_races.inc from the ELF: the Adventure's town races, rows 0-27 of
D_002BDDD0 (16 bytes: course, cars, laps, rank, +4 the race's setup, +8 its task, +0xC a function), with each row's
setup: +0 the opponents' list ((group, index) of D_002C22C8 for cars - 1 cars) and +4 the opponents' 16-byte parts
record (Car_Init: +0x180 = setup + 4, the part flags +0x190 = setup + 0x12, the record's +0xE). Rows 0-27 are the
towns' races and 28-34 the GrandPrix; races 35 on are the events, whose rows Race_Setup takes from D_002BE018
(16 (race - 35) on, the same layout; a one-car event has no setup). Rows share lists, so each list is written once,
named by address.

    python -I scripts/elf/gen_adventure_races.py
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# The extracted disc: OriginalGameFiles next to the repo, or the folder in RTAGLASS_GAME.
GAME = os.environ.get('RTAGLASS_GAME', os.path.join(ROOT, '..', 'OriginalGameFiles'))
ELF = os.path.join(GAME, 'SLUS_203.98')
OUT = os.path.join(ROOT, 'src', 'game', 'story', 'adventure_races.inc')
TABLE = 0x002BDDD0
ROWS = 35
EVENTS = 0x002BE018
EVENT_ROWS = 21   # races 35-55
TOWNS = 0x002BE000   # D_002BE000: (first, count) by town

elf = open(ELF, 'rb').read()
phoff, = struct.unpack_from('<I', elf, 0x1C)
count, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<6I', elf, phoff + 32 * i)[1:5] for i in range(count)]


def rd(va, n):
    for off, vaddr, _pa, size in segs:
        if vaddr <= va < vaddr + size:
            return elf[off + va - vaddr:off + va - vaddr + n]
    raise ValueError(hex(va))


towns = rd(TOWNS, 20)
first_of = {towns[2 * t]: t for t in range(10) if towns[2 * t + 1]}
rows = []
lists = {}
for i in range(ROWS + EVENT_ROWS):
    row = TABLE + 16 * i if i < ROWS else EVENTS + 16 * (i - ROWS)
    course, cars, laps, rank, setup, _task, _fn = struct.unpack('<4B3I', rd(row, 16))
    if not setup:
        rows.append((course, cars, laps, rank, None, bytes(16)))
        continue
    lst, = struct.unpack('<I', rd(setup, 4))
    lists[lst] = max(lists.get(lst, 0), cars - 1)
    rows.append((course, cars, laps, rank, lst, rd(setup + 4, 16)))

lines = ['// Generated by scripts/elf/gen_adventure_races.py from the ELF (SLUS_203.98): the Adventure\'s races, rows',
         '// 0-34 of D_002BDDD0 and the events 35-55 (D_002BE018), with each row\'s setup (+4): the opponents\' list,',
         '// (group, index) of D_002C22C8, and their parts record (setup + 4; its +0xE the part flags).']
for lst in sorted(lists):
    pairs = [tuple(rd(lst + 2 * k, 2)) for k in range(lists[lst])]
    lines.append('const unsigned char kOpponents%06X[%d][2] = {' % (lst, len(pairs)))
    for k in range(0, len(pairs), 12):
        lines.append('    ' + ' '.join('{%d, %d},' % p for p in pairs[k:k + 12]))
    lines.append('};')
lines.append('const AdventureRace kRaces[kAdventureRaces] = {')
for i, (course, cars, laps, rank, lst, parts) in enumerate(rows):
    if i in first_of:
        lines.append('    // town %d' % first_of[i])
    if i == ROWS:
        lines.append('    // the events (D_002BE018)')
    name = 'kOpponents%06X' % lst if lst else 'nullptr'
    lines.append('    {0x%02X, %d, %d, %d, %s, {%s}},' %
                 (course, cars, laps, rank, name, ', '.join('0x%02X' % b for b in parts)))
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(rows), 'rows,', len(lists), 'lists')
