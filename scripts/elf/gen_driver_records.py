"""Writes src/game/race/driver_records.inc from the ELF: the driver records D_002C22C8[group] + 16 x index,
groups 1-31 (groups 0, 28 and 30 are none), each {paint (+0), body (+4), name (+0xC)}. A group's records run up to the next
group's; the last's up to the pointer table itself.

    python -I scripts/elf/gen_driver_records.py
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
# The extracted disc: OriginalGameFiles next to the repo, or the folder in RTAGLASS_GAME.
GAME = os.environ.get('RTAGLASS_GAME', os.path.join(ROOT, '..', 'OriginalGameFiles'))
ELF = os.path.join(GAME, 'SLUS_203.98')
OUT = os.path.join(ROOT, 'src', 'game', 'race', 'driver_records.inc')
TABLE = 0x002C22C8
GROUPS = 32

elf = open(ELF, 'rb').read()
phoff, = struct.unpack_from('<I', elf, 0x1C)
count, = struct.unpack_from('<H', elf, 0x2C)
segs = [struct.unpack_from('<6I', elf, phoff + 32 * i)[1:5] for i in range(count)]


def rd(va, n):
    for off, vaddr, _pa, size in segs:
        if vaddr <= va < vaddr + size:
            return elf[off + va - vaddr:off + va - vaddr + n]
    raise ValueError(hex(va))


def cstr(va):
    b = rd(va, 64).split(b'\0')[0]
    return ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92, 63) else '\\%03o' % c for c in b)


ptrs = list(struct.unpack('<%dI' % GROUPS, rd(TABLE, 4 * GROUPS)))
ends = sorted(set(p for p in ptrs if p) | {TABLE})
lines = ['// Generated by scripts/elf/gen_driver_records.py from the ELF (SLUS_203.98): the driver records',
         '// D_002C22C8[group] + 16 x index, groups 1-31 (groups 0, 28 and 30 are none): {paint, body, name}. Each group\'s records run',
         '// up to the next group\'s; the last\'s up to the pointer table itself.']
sizes = []
for g, p in enumerate(ptrs):
    if not p:
        sizes.append(0)
        continue
    end = min(e for e in ends if e > p)
    n = (end - p) // 16
    sizes.append(n)
    lines.append('const CarRecord kDriverGroup%d[%d] = {' % (g, n))
    for i in range(n):
        paint, body, _z, name = struct.unpack('<4I', rd(p + 16 * i, 16))
        lines.append('    {0x%06X, %d, "%s"},' % (paint & 0xFFFFFF, body & 0xFF, cstr(name) if name else ''))
    lines.append('};')
lines.append('const CarRecord* const kDriverGroups[%d] = {' % GROUPS)
lines.append('    ' + ', '.join('nullptr' if not p else 'kDriverGroup%d' % g for g, p in enumerate(ptrs)) + ',')
lines.append('};')
lines.append('const int kDriverGroupSize[%d] = {' % GROUPS)
lines.append('    ' + ', '.join(str(s) for s in sizes) + ',')
lines.append('};')
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT, sum(sizes), 'records')
